import io
from datetime import datetime

def generate_pdf_report(entry, settings, user_info):
    """
    Generate a professional PDF report for UV-Vis spectral analysis using ReportLab.
    Returns PDF file bytes.
    """
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY, TA_LEFT

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=A4,
            topMargin=1.2 * cm, bottomMargin=1.5 * cm,
            leftMargin=1.5 * cm, rightMargin=1.5 * cm
        )

        story = []

        title_style = ParagraphStyle('title', fontSize=22, fontName='Helvetica-Bold',
                                      textColor=colors.HexColor('#1e3a5f'), spaceAfter=4)
        subtitle_style = ParagraphStyle('subtitle', fontSize=11,
                                         textColor=colors.HexColor('#64748b'), spaceAfter=2)
        section_style = ParagraphStyle('section', fontSize=13, fontName='Helvetica-Bold',
                                        textColor=colors.HexColor('#1e3a5f'),
                                        spaceBefore=16, spaceAfter=6)
        body_style = ParagraphStyle('body', fontSize=10, leading=16,
                                     textColor=colors.HexColor('#334155'),
                                     alignment=TA_JUSTIFY)
        caption_style = ParagraphStyle('caption', fontSize=9,
                                        textColor=colors.HexColor('#94a3b8'),
                                        alignment=TA_CENTER)

        # Header area
        story.append(Paragraph('AI UV-Vis Spectrum Analysis Report', title_style))
        org_name = settings.get('org_name', 'Laboratory')
        story.append(Paragraph(
            f"Generated by {org_name} | "
            f"{datetime.now().strftime('%B %d, %Y at %H:%M')}", subtitle_style))
        story.append(HRFlowable(width='100%', thickness=2,
                                 color=colors.HexColor('#3b82f6'), spaceAfter=12))

        # Analyst & Report Metadata Table
        story.append(Paragraph('Report Information', section_style))
        info_data = [
            ['Field', 'Value'],
            ['Date & Time', entry.get('timestamp', datetime.now().strftime('%Y-%m-%d %H:%M:%S'))],
            ['Analyst / Scientist', user_info.get('name', settings.get('scientist_name', 'N/A'))],
            ['Organization', org_name],
            ['Sample File', entry.get('filename', 'N/A')],
            ['Report ID', str(entry.get('id', 'N/A'))[:16] + '...'],
        ]
        info_table = Table(info_data, colWidths=[4 * cm, 13.5 * cm])
        info_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e3a5f')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 10),
            ('FONTNAME', (0, 1), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 1), (-1, -1), 9),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1),
             [colors.white, colors.HexColor('#f8fafc')]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 7),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        story.append(info_table)

        # Analysis Results Table
        story.append(Paragraph('Analysis Results', section_style))
        st = entry.get('status', 'N/A')
        status_color = (colors.HexColor('#16a34a') if st == 'SAFE'
                        else colors.HexColor('#d97706') if st == 'MODERATE'
                        else colors.HexColor('#dc2626'))
        confidence = entry.get('confidence_score', 0)

        results_data = [
            ['Parameter', 'Value'],
            ['Peak Wavelength (λmax)', f"{entry.get('peak_wavelength', 'N/A')} nm"],
            ['Peak Absorbance', f"{entry.get('peak_absorbance', 'N/A')} AU"],
            ['Predicted Concentration', f"{entry.get('predicted_concentration', 'N/A')} ppm"],
            ['ML Algorithm', entry.get('algorithm', 'Random Forest Regressor')],
            ['Model Accuracy (R²)', f"{entry.get('accuracy_percentage', 'N/A')}%"],
            ['RMSE', str(entry.get('rmse', 'N/A'))],
            ['MAE', str(entry.get('mae', 'N/A'))],
            ['AI Prediction Confidence', f"{confidence}%"],
            ['Risk Status', st],
        ]
        results_table = Table(results_data, colWidths=[6 * cm, 11.5 * cm])
        ts = TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e3a5f')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 10),
            ('FONTNAME', (0, 1), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 1), (-1, -1), 10),
            ('ROWBACKGROUNDS', (0, 1), (-1, -2),
             [colors.white, colors.HexColor('#f8fafc')]),
            ('BACKGROUND', (0, -1), (-1, -1), colors.HexColor('#f0fdf4') if st == 'SAFE'
             else colors.HexColor('#fffbeb') if st == 'MODERATE'
             else colors.HexColor('#fef2f2')),
            ('TEXTCOLOR', (1, -1), (1, -1), status_color),
            ('FONTNAME', (1, -1), (1, -1), 'Helvetica-Bold'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 8),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ])
        results_table.setStyle(ts)
        story.append(results_table)

        # Scientific Interpretation
        story.append(Paragraph('Scientific Interpretation', section_style))
        interpretation = entry.get('interpretation', 'No interpretation provided.')
        story.append(Paragraph(interpretation, body_style))

        # Conclusion & Recommendation
        story.append(Paragraph('Conclusion & Recommendation', section_style))
        conclusion = entry.get('conclusion', 'No conclusion provided.')
        story.append(Paragraph(conclusion, body_style))

        # Footer
        story.append(Spacer(1, 0.5 * cm))
        story.append(HRFlowable(width='100%', thickness=0.5,
                                 color=colors.HexColor('#e2e8f0')))
        story.append(Spacer(1, 0.25 * cm))
        story.append(Paragraph(
            f"AI UV-Vis Spectrum Analyzer | {org_name} | Verification Key: {entry.get('id', '')[:12]} | Confidential",
            caption_style
        ))

        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()
    except ImportError:
        return None
